export default function LegalPage() {
  const router = useRouter();
  const [activeId, setActiveId] = useState(LEGAL_SECTIONS[0].id);
  const active = LEGAL_SECTIONS.find((s) => s.id === activeId) ?? LEGAL_SECTIONS[0];

  useEffect(() => {
    document.title = `${active.title} — GenGO`;
  }, [active.title]);

  const goBack = () => {
    if (typeof window !== "undefined" && window.history.length > 1) router.back();
    else router.push("/");
  };

  return (
    <div className="min-h-screen">
      <div className="ds-aurora" aria-hidden />
      <AppHeader />
      <AppShell>
        <div
          aria-hidden
          className="pointer-events-none absolute inset-x-0 top-0 h-[440px] overflow-hidden"
        >
          <div className="ds-hero-glow absolute inset-0" />
          <div className="ds-dotgrid ds-dotgrid-fade absolute inset-0 opacity-[0.14]" />
        </div>

        <div className="relative mx-auto max-w-5xl px-4 pt-4 pb-10 sm:py-8">
          <BackButton onClick={goBack} className="-ml-2 mb-4" />

          <header className="mb-6">
            <span className="ds-overline ds-overline-accent">GenGO Studio</span>
            <h1 className="ds-h1 mt-1">Правовая информация</h1>
            <p className="mt-2 max-w-xl text-sm text-muted-foreground">
              Условия использования, конфиденциальность и другие юридические документы сервиса.
            </p>
          </header>

          <div className="grid gap-6 lg:grid-cols-[220px_1fr]">
            {/* Section nav — vertical list on desktop, horizontal scroll strip
                on mobile. Same active-pill convention as the main sidebar. */}
            <nav className="lg:sticky lg:top-20 lg:self-start">
              <ul className="flex gap-1.5 overflow-x-auto pb-2 lg:flex-col lg:overflow-visible lg:pb-0">
                {LEGAL_SECTIONS.map((s) => {
                  const Icon = s.icon;
                  const isActive = s.id === activeId;
                  return (
                    <li key={s.id} className="shrink-0 lg:shrink">
                      <button
                        type="button"
                        onClick={() => setActiveId(s.id)}
                        aria-current={isActive ? "page" : undefined}
                        className={`flex h-10 w-full items-center gap-2.5 whitespace-nowrap rounded-lg px-3 text-left text-sm transition ${
                          isActive
                            ? "bg-[var(--lime-tint)] font-medium text-accent-green"
                            : "text-muted-foreground hover:bg-white/5 hover:text-foreground"
                        }`}
                      >
                        <Icon className={`h-4 w-4 shrink-0 ${isActive ? "text-accent-green" : ""}`} />
                        {s.label}
                      </button>
                    </li>
                  );
                })}
              </ul>
            </nav>

            <Card>
              <CardHeader>
                <CardTitle>{active.title}</CardTitle>
              </CardHeader>
              <CardContent className="space-y-5">
                {active.blocks.map((b, i) => (
                  <div key={i}>
                    {b.h ? <h3 className="ds-h4 mb-1.5">{b.h}</h3> : null}
                    <div className="space-y-1.5">
                      {b.p.map((line, j) => (
                        <p key={j} className="text-sm leading-relaxed text-muted-foreground">
                          {line}
                        </p>
                      ))}
                    </div>
                  </div>
                ))}
              </CardContent>
            </Card>
          </div>
        </div>
      </AppShell>
    </div>
  );
}
