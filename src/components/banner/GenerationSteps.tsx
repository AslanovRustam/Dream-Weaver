"use client";

import { useMemo } from "react";

/**
 * Что показывать, пока идёт генерация.
 *
 * Ожидание в 20–40 секунд без слов читается как зависший экран, а честное
 * «ждём ответа провайдера» ничего не добавляет: повлиять человек всё равно не
 * может. Поэтому рассказываем, из чего складывается картинка, — по-человечески
 * и без ложной точности: это не настоящие этапы, и выдавать их за прогресс мы
 * не пытаемся, оттого и счётчик секунд рядом.
 */
const STEPS: string[] = [
  "Раскладываем композицию…",
  "Ищем ракурс поэффектнее…",
  "Ставим свет как в кино…",
  "Отмеряем блеск: чтобы дорого, но не аляписто…",
  "Следим, чтобы кнопка не уехала за край…",
  "Уговариваем нейросеть писать без опечаток…",
  "Добавляем искр — ровно столько, чтобы не пожар…",
  "Отговариваем её дорисовать лишние надписи…",
  "Проверяем, что логотип остался вашим…",
  "Наводим резкость на главное…",
];

export function GenerationSteps({
  seconds,
  done,
  total,
}: {
  seconds: number;
  /** Сколько вариантов уже готово (для пачки). */
  done: number;
  /** Сколько всего заказали. 1 — обычная одиночная генерация. */
  total: number;
}) {
  // Порядок свой на каждый запуск: одна и та же вереница фраз на третьей
  // генерации подряд начинает раздражать. Секунды уже тикают снаружи, своего
  // таймера заводить не нужно.
  const order = useMemo(() => [...STEPS].sort(() => Math.random() - 0.5), []);
  const line = order[Math.floor(seconds / 5) % order.length];

  return (
    <>
      <p className="text-sm font-medium text-foreground">{line}</p>
      <p className="text-xs text-muted-foreground">
        {total > 1 ? `Готово ${done} из ${total} · ` : ""}
        {seconds >= 40 ? `дольше обычного… ${seconds} с` : `обычно 10–30 секунд · ${seconds} с`}
      </p>
    </>
  );
}
